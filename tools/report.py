REPO = claimcheck.REPO
SPEC = claimcheck.SPEC
REGISTRY = claimcheck.REGISTRY
ALLOWLIST = claimcheck.ALLOWLIST
TEMPLATES = "docs/templates"
FIGURES = "docs/figures"
MANIFEST = "artifacts/figures/manifest.json"
GENERATOR = "tools/report.py"
TOP_FIELDS = {"comment", "claims", "templates", "figures"}
CLAIM_FIELDS = {"artifact", "path", "format", "note"}
FIGURE_FIELDS = {"title", "alt", "axis_label", "domain", "tick_format", "bars"}
BAR_FIELDS = {"label", "value", "lo", "hi"}
NAME_RE = re.compile(r"[a-z0-9]+(?:[-_][a-z0-9]+)*")
ARTIFACT_RE = re.compile(r"artifacts/[A-Za-z0-9_.@=+-]+(?:/[A-Za-z0-9_.@=+-]+)*\.jsonl?")
INDEX_RE = re.compile(r"-?[0-9]+")
PLACEHOLDER_RE = re.compile(r"\{\{([^{}]*)\}\}")
NEAR_MISS_RE = re.compile(r"\s*(?:claims?|figures?)\s*:", re.I)
BANNER = (
    "<!-- generated by tools/report.py from {template}; edit the template, then run make report -->"
)


@dataclass(frozen=True)
class Selector:
    """A parsed claim path."""

    steps: tuple[str, ...]
    op: str = ""  # "", "len", or "count"
    count_field: str = ""
    count_value: Any = None


@dataclass(frozen=True)
class ClaimSpec:
    """A declared claim."""

    key: str
    artifact: str
    path: str
    selector: Selector
    format: str


@dataclass(frozen=True)
class BarSpec:
    """A declared bar: a label and the claim keys of its value and interval."""

    label: str
    value: str
    lo: str | None = None
    hi: str | None = None


@dataclass(frozen=True)
class FigureSpec:
    """A declared figure."""

    name: str
    title: str
    alt: str
    bars: tuple[BarSpec, ...]
    axis_label: str | None = None
    domain: tuple[float, float] | None = None
    tick_format: str | None = None


@dataclass
class Spec:
    """docs/claims/spec.json, validated."""

    claims: dict[str, ClaimSpec] = field(default_factory=dict)
    templates: dict[str, str | None] = field(default_factory=dict)
    figures: dict[str, FigureSpec] = field(default_factory=dict)


@dataclass(frozen=True)
class Claim:
    """A claim resolved from its artifact now."""

    key: str
    value: str
    raw: float
    artifact: str
    path: str
    artifact_sha256: str


@dataclass(frozen=True)
class Rendered:
    """A document rendered from a template."""

    template: str
    text: str
    claims: int
    figures: int


@dataclass
class Build:
    """Everything ``make report`` would write, computed in memory."""

    spec: Spec
    claims: dict[str, Claim] = field(default_factory=dict)
    figures: dict[str, str] = field(default_factory=dict)
    docs: dict[str, Rendered] = field(default_factory=dict)
    examples: list[str] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)

    @property
    def registry(self) -> dict[str, dict[str, str]]:
        """The registry document."""
        return {
            k: {
                "artifact": c.artifact,
                "artifact_sha256": c.artifact_sha256,
                "path": c.path,
                "value": c.value,
            }
            for k, c in sorted(self.claims.items())
        }

    @property
    def manifest(self) -> list[dict[str, str]]:
        """The figure manifest, sorted by path."""
        return [
            {"generator": GENERATOR, "path": rel, "sha256": sha256_text(svg)}
            for rel, svg in sorted(self.figures.items())
        ]


def sha256_text(text: str) -> str:
    """Hex SHA-256 of UTF-8 text."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def json_type(value: Any) -> str:
    """The JSON type name of a parsed value."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, int | float):
        return "number"
    if isinstance(value, str):
        return "string"
    return "array" if isinstance(value, list) else "object"


def json_equal(a: Any, b: Any) -> bool:
    """JSON equality: booleans never equal numbers; 1 equals 1.0."""
    if isinstance(a, bool) or isinstance(b, bool):
        return isinstance(a, bool) and isinstance(b, bool) and a == b
    if isinstance(a, int | float) and isinstance(b, int | float):
        return a == b
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(json_equal(x, y) for x, y in zip(a, b, strict=True))
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(json_equal(a[k], b[k]) for k in a)
    return type(a) is type(b) and a == b


def parse_match(raw: str) -> Any:
    """The value in ``|count:field=value``: JSON when it parses, else the raw string."""
    try:
        return json.loads(raw)
    except ValueError:
        return raw


def parse_path(text: str) -> Selector:
    """Parse a claim path such as ``e1.rate.ci.-1``, ``tasks|len``, ``v|count:kind=x``."""
    selector, bar, op = text.partition("|")
    steps = tuple(selector.split(".")) if selector else ()
    if any(not s for s in steps):
        raise ValueError(f"path {text!r} has an empty component")
    if not bar:
        return Selector(steps)
    if op == "len":
        return Selector(steps, "len")
    if op.startswith("count:") and "|" not in op:
        name, eq, raw = op[len("count:") :].partition("=")
        if name and eq:
            return Selector(steps, "count", name, parse_match(raw))
    raise ValueError(f"path {text!r}: the suffix must be |len or |count:field=value")


def resolve(data: Any, sel: Selector) -> Any:
    """The value ``sel`` selects in a parsed artifact (ValueError if it does not resolve)."""
    cur = data
    for i, step in enumerate(sel.steps):
        here = ".".join(sel.steps[:i]) or "the document root"
        if isinstance(cur, list):
            if not INDEX_RE.fullmatch(step):
                raise ValueError(f"{here} is a list and {step!r} is not an index")
            idx = int(step)
            if not -len(cur) <= idx < len(cur):
                raise ValueError(f"index {idx} is out of range for {here} (length {len(cur)})")
            cur = cur[idx]
        elif isinstance(cur, dict):
            if step not in cur:
                raise ValueError(f"{here} has no key {step!r}")
            cur = cur[step]
        else:
            raise ValueError(f"{here} is a {json_type(cur)}, so {step!r} cannot select in it")
    if sel.op == "len":
        if not isinstance(cur, list | dict):
            raise ValueError(f"|len needs a list or object, found a {json_type(cur)}")
        return len(cur)
    if sel.op == "count":
        if not isinstance(cur, list) or not all(isinstance(x, dict) for x in cur):
            raise ValueError("|count needs a list of objects")
        f, want = sel.count_field, sel.count_value
        return sum(1 for x in cur if f in x and json_equal(x[f], want))
    return cur


def check_format(fmt: str) -> None:
    """Raise ValueError unless ``fmt`` has exactly one plain replacement field."""
    try:
        parts = list(string.Formatter().parse(fmt))
    except ValueError as exc:
        raise ValueError(f"format {fmt!r} is not a Python format string: {exc}") from exc
    fields = [p for p in parts if p[1] is not None]
    if (
        len(fields) != 1
        or fields[0][1] != ""
        or fields[0][3] is not None
        or "{" in (fields[0][2] or "")
    ):
        raise ValueError(f"format {fmt!r} needs exactly one field such as {{:.2f}} or {{}}")


def format_value(value: Any, fmt: str) -> str:
    """Format a claim value; the result must be one number token (see tools/claimcheck.py)."""
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise ValueError(f"the value is a {json_type(value)}, not a number")
    if not math.isfinite(value):
        raise ValueError("the value is not a finite number")
    check_format(fmt)
    try:
        text = fmt.format(value)
    except (ValueError, TypeError) as exc:
        raise ValueError(f"format {fmt!r} does not apply to {value!r}: {exc}") from exc
    if not claimcheck.NUMBER_FULL.fullmatch(text):
        raise ValueError(f"format {fmt!r} gives {text!r}, which is not a single number token")
    return text


def safe_relpath(path: str) -> bool:
    """A relative POSIX path without empty, ``.``, or ``..`` components."""
    parts = path.split("/")
    return not path.startswith("/") and all(p not in ("", ".", "..") for p in parts)


def parse_claim(key: str, raw: Any) -> tuple[ClaimSpec | None, list[str]]:
    """Validate one claim declaration."""
    where = f"{SPEC}: claim {key}"
    if not claimcheck.KEY_RE.fullmatch(key):
        return None, [f"{where}: keys are letters and digits joined by single . _ or -"]
    if not isinstance(raw, dict):
        return None, [f"{where} must be an object"]
    problems = [f"{where}: unknown field {k!r}" for k in sorted(set(raw) - CLAIM_FIELDS)]
    if "note" in raw and not isinstance(raw["note"], str):
        problems.append(f"{where}: note must be a string")
    artifact, path, fmt = raw.get("artifact"), raw.get("path"), raw.get("format")
    if not (isinstance(artifact, str) and isinstance(path, str) and isinstance(fmt, str)):
        return None, [*problems, f"{where}: artifact, path, and format must all be strings"]
    if not ARTIFACT_RE.fullmatch(artifact) or not safe_relpath(artifact):
        problems.append(f"{where}: artifact must be a .json or .jsonl file under artifacts/")
    selector: Selector | None = None
    try:
        check_format(fmt)
    except ValueError as exc:
        problems.append(f"{where}: {exc}")
    try:
        selector = parse_path(path)
    except ValueError as exc:
        problems.append(f"{where}: {exc}")
    if problems or selector is None:
        return None, problems
    return ClaimSpec(key, artifact, path, selector, fmt), []


def check_mapping(template: str, output: Any) -> str | None:
    """The problem with one ``templates`` entry, or None."""
    where = f"{SPEC}: template {template!r}"
    if not template.endswith(".md.in") or not safe_relpath(template):
        return f"{where} must be a relative path under {TEMPLATES}/ ending in .md.in"
    stars = template.count("*")
    if stars > 1 or "*" in posixpath.dirname(template):
        return f"{where}: at most one * and only in the file name"
    if output is None:
        return None
    if not isinstance(output, str) or not output.endswith(".md") or not safe_relpath(output):
        return f"{where}: the output must be a relative path ending in .md, or null"
    if output.count("*") != stars or "*" in posixpath.dirname(output):
        return f"{where}: use one * in the file name of both the template and the output, or none"
    if output.startswith((f"{TEMPLATES}/", "artifacts/")):
        return f"{where}: the output must not be under {TEMPLATES}/ or artifacts/"
    return None


def figure_text(value: Any, what: str, where: str, required: bool) -> tuple[str | None, list[str]]:
    """A one-line figure string usable inside Markdown image alt text."""
    if value is None and not required:
        return None, []
    if not isinstance(value, str) or not value.strip():
        return None, [f"{where}: {what} must be a non-empty string"]
    if any(c in value for c in "[]\n"):
        return None, [f"{where}: {what} must be one line without [ or ]"]
    return value, []


def parse_domain(value: Any, where: str) -> tuple[tuple[float, float] | None, list[str]]:
    """``[low, high]`` with low < high, or None."""
    if value is None:
        return None, []
    ok = (
        isinstance(value, list)
        and len(value) == 2
        and all(isinstance(v, int | float) and not isinstance(v, bool) for v in value)
        and all(math.isfinite(v) for v in value)
        and value[0] < value[1]
    )
    if not ok:
        return None, [f"{where}: domain must be [low, high] with finite numbers, low < high"]
    return (float(value[0]), float(value[1])), []


def parse_figure(
    name: str, raw: Any, claims: dict[str, ClaimSpec]
) -> tuple[FigureSpec | None, list[str]]:
    """Validate one figure declaration."""
    where = f"{SPEC}: figure {name}"
    if not NAME_RE.fullmatch(name):
        return None, [f"{where}: names are lowercase letters and digits joined by - or _"]
    if not isinstance(raw, dict):
        return None, [f"{where} must be an object"]
    problems = [f"{where}: unknown field {k!r}" for k in sorted(set(raw) - FIGURE_FIELDS)]
    title, p1 = figure_text(raw.get("title"), "title", where, True)
    alt, p2 = figure_text(raw.get("alt", raw.get("title")), "alt", where, True)
    axis, p3 = figure_text(raw.get("axis_label"), "axis_label", where, False)
    domain, p4 = parse_domain(raw.get("domain"), where)
    problems += p1 + p2 + p3 + p4
    tick_format = raw.get("tick_format")
    if tick_format is not None:
        try:
            if not isinstance(tick_format, str):
                raise ValueError("tick_format must be a string")
            check_format(tick_format)
            tick_format.format(0.5)
        except (ValueError, TypeError) as exc:
            problems.append(f"{where}: {exc}")
    bars_raw = raw.get("bars")
    bars: list[BarSpec] = []
    if not isinstance(bars_raw, list) or not bars_raw:
        problems.append(f"{where}: bars must be a non-empty list")
        bars_raw = []
    for i, b in enumerate(bars_raw):
        at = f"{where} bar {i}"
        if not isinstance(b, dict):
            problems.append(f"{at} must be an object")
            continue
        problems += [f"{at}: unknown field {k!r}" for k in sorted(set(b) - BAR_FIELDS)]
        label, p = figure_text(b.get("label"), "label", at, True)
        problems += p
        keys = [b.get("value"), b.get("lo"), b.get("hi")]
        if not isinstance(keys[0], str) or keys[0] not in claims:
            problems.append(f"{at}: value must name a declared claim")
        if (keys[1] is None) != (keys[2] is None):
            problems.append(f"{at}: give both lo and hi, or neither")
        for k in keys[1:]:
            if k is not None and (not isinstance(k, str) or k not in claims):
                problems.append(f"{at}: lo and hi must name declared claims")
        if label is not None and isinstance(keys[0], str):
            lo, hi = keys[1], keys[2]
            bars.append(
                BarSpec(
                    label,
                    keys[0],
                    lo if isinstance(lo, str) else None,
                    hi if isinstance(hi, str) else None,
                )
            )
    if problems or title is None or alt is None:
        return None, problems
    fmt = tick_format if isinstance(tick_format, str) else None
    return FigureSpec(name, title, alt, tuple(bars), axis, domain, fmt), []


def load_spec(root: Path) -> tuple[Spec, list[str]]:
    """Read and validate docs/claims/spec.json."""
    spec = Spec()
    path = root / SPEC
    if not path.is_file():
        return spec, [f"{SPEC} missing"]
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except ValueError as exc:
        return spec, [f"{SPEC} is not valid JSON: {exc}"]
    if not isinstance(data, dict):
        return spec, [f"{SPEC} must be a JSON object"]
    problems = [f"{SPEC}: unknown top-level key {k!r}" for k in sorted(set(data) - TOP_FIELDS)]
    sections: dict[str, dict[str, Any]] = {}
    for name in ("claims", "templates", "figures"):
        value = data.get(name, {})
        if isinstance(value, dict):
            sections[name] = value
        else:
            problems.append(f"{SPEC}: {name} must be an object")
            sections[name] = {}
    for key, raw in sorted(sections["claims"].items()):
        claim, p = parse_claim(key, raw)
        problems += p
        if claim is not None:
            spec.claims[key] = claim
    for template, output in sorted(sections["templates"].items()):
        why = check_mapping(template, output)
        if why:
            problems.append(why)
        else:
            spec.templates[template] = output
    for name, raw in sorted(sections["figures"].items()):
        figure, p = parse_figure(name, raw, spec.claims)
        problems += p
        if figure is not None:
            spec.figures[name] = figure
    return spec, problems


def load_artifact(root: Path, rel: str) -> tuple[Any, str] | str:
    """(parsed JSON, SHA-256 of the bytes) of an artifact, or the reason it cannot be read.

    A ``.jsonl`` artifact is the list of its records, one JSON value per non-blank line.
    """
    path = root / rel
    if not path.is_file():
        return f"{rel} missing"
    blob = path.read_bytes()
    try:
        text = blob.decode("utf-8")
    except UnicodeDecodeError as exc:
        return f"{rel} is not UTF-8: {exc}"
    if not rel.endswith(".jsonl"):
        try:
            return json.loads(text), hashlib.sha256(blob).hexdigest()
        except ValueError as exc:
            return f"{rel} is not valid JSON: {exc}"
    records: list[Any] = []
    for i, line in enumerate(text.splitlines(), start=1):
        if not line.strip():
            continue
        try:
            records.append(json.loads(line))
        except ValueError as exc:
            return f"{rel}:{i} is not valid JSON: {exc}"
    return records, hashlib.sha256(blob).hexdigest()


def resolve_claims(root: Path, spec: Spec) -> tuple[dict[str, Claim], list[str]]:
    """Every declared claim, resolved and formatted from its artifact now."""
    cache: dict[str, tuple[Any, str] | str] = {}
    claims: dict[str, Claim] = {}
    problems: list[str] = []
    for key, c in sorted(spec.claims.items()):
        if c.artifact not in cache:
            cache[c.artifact] = load_artifact(root, c.artifact)
        loaded = cache[c.artifact]
        if isinstance(loaded, str):
            problems.append(f"claim {key}: {loaded}")
            continue
        data, sha = loaded
        try:
            raw = resolve(data, c.selector)
            text = format_value(raw, c.format)
        except ValueError as exc:
            problems.append(f"claim {key}: {c.artifact} {c.path!r}: {exc}")
            continue
        claims[key] = Claim(key, text, raw, c.artifact, c.path, sha)
    return claims, problems


def text_numbers(text: str, where: str, allow: Sequence[claimcheck.AllowEntry]) -> list[str]:
    """Unbacked numbers in a figure string (figures may only show numbers from claims).

    The string is read as the middle of a sentence, so a leading ``1.`` or ``#`` is not
    taken for a list marker or a heading.
    """
    found = claimcheck.check_text(f"x {text}", where, {}, allow).problems
    return [p.replace(f"{where}:1: ", f"{where}: ", 1) for p in found]


def draw_figures(
    spec: Spec, claims: dict[str, Claim], allow: Sequence[claimcheck.AllowEntry]
) -> tuple[dict[str, str], list[str]]:
    """Every declared figure as SVG text keyed by its repository path."""
    figures: dict[str, str] = {}
    problems: list[str] = []
    for name, fig in sorted(spec.figures.items()):
        where = f"figure {name}"
        texts = [("title", fig.title), ("alt", fig.alt), ("axis_label", fig.axis_label or "")]
        texts += [(f"bar label {b.label!r}", b.label) for b in fig.bars]
        found = [p for what, t in texts for p in text_numbers(t, f"{where} {what}", allow)]
        keys = sorted({k for b in fig.bars for k in (b.value, b.lo, b.hi) if k})
        unresolved = [k for k in keys if k not in claims]
        if unresolved:
            found.append(f"{where}: claims {unresolved} did not resolve")
        if found:
            problems += found
            continue
        bars = [
            svgchart.Bar(
                b.label,
                claims[b.value].raw,
                claims[b.value].value,
                claims[b.lo].raw if b.lo else None,
                claims[b.hi].raw if b.hi else None,
                claims[b.lo].value if b.lo else "",
                claims[b.hi].value if b.hi else "",
            )
            for b in fig.bars
        ]
        try:
            svg = svgchart.horizontal_bars(
                name,
                fig.title,
                bars,
                domain=fig.domain,
                axis_label=fig.axis_label,
                tick_format=fig.tick_format,
            )
        except ValueError as exc:
            problems.append(f"{where}: {exc}")
            continue
        figures[f"{FIGURES}/{name}.svg"] = svg
    return figures, problems


def match_template(rel: str, pattern: str) -> str | None:
    """What the ``*`` in ``pattern`` stands for in ``rel`` ('' for a literal match), or None."""
    if "*" not in pattern:
        return "" if rel == pattern else None
    prefix, suffix = pattern.split("*")
    if not (rel.startswith(prefix) and rel.endswith(suffix)):
        return None
    stem = rel[len(prefix) : len(rel) - len(suffix)]
    return stem if stem and "/" not in stem else None


def render(
    text: str,
    template: str,
    output: str,
    spec: Spec,
    claims: dict[str, Claim],
    figures: dict[str, str],
) -> tuple[Rendered | None, list[str]]:
    """Replace the placeholders of one template; append the generated-file banner."""
    problems: list[str] = []
    counts = {"claim": 0, "figure": 0}

    def sub(m: re.Match[str]) -> str:
        body = m.group(1)
        kind, sep, name = body.partition(":")
        if sep and kind == "claim":
            claim = claims.get(name)
            if name not in spec.claims:
                problems.append(f"{template}: unknown claim {name!r} (declare it in {SPEC})")
            elif claim is None:
                problems.append(f"{template}: claim {name} did not resolve")
            else:
                counts["claim"] += 1
                return f"{claim.value}<!--claim:{name}-->"
            return m.group(0)
        if sep and kind == "figure":
            path = f"{FIGURES}/{name}.svg"
            fig = spec.figures.get(name)
            if fig is None:
                problems.append(f"{template}: unknown figure {name!r} (declare it in {SPEC})")
            elif path not in figures:
                problems.append(f"{template}: figure {name} was not drawn")
            else:
                counts["figure"] += 1
                link = posixpath.relpath(path, posixpath.dirname(output) or ".")
                return f"![{fig.alt}]({link})"
            return m.group(0)
        if NEAR_MISS_RE.match(body):
            problems.append(
                f"{template}: malformed placeholder {m.group(0)!r} "
                "(write {{claim:KEY}} or {{figure:NAME}})"
            )
        return m.group(0)

    out = PLACEHOLDER_RE.sub(sub, text)
    found, malformed = claimcheck.claim_occurrences(out)
    problems += [f"{template}:{p}" for p in malformed]
    for occ in found:
        claim = claims.get(occ.key)
        where = f"{template}:{occ.line}"
        if occ.key not in spec.claims:
            problems.append(f"{where}: marker for unknown claim {occ.key} (declare it in {SPEC})")
        elif claim is None:
            problems.append(f"{where}: marker for claim {occ.key}, which did not resolve")
        elif occ.shown != claim.value:
            shown = "no number token" if occ.shown is None else occ.shown
            problems.append(
                f"{where}: claim {occ.key} renders as {shown}, not {claim.value} "
                "(keep the placeholder apart from letters and digits before it)"
            )
    if problems:
        return None, problems
    out = out.rstrip("\n") + "\n\n" + BANNER.format(template=template) + "\n"
    return Rendered(template, out, counts["claim"], counts["figure"]), []


def render_templates(
    root: Path, spec: Spec, claims: dict[str, Claim], figures: dict[str, str]
) -> tuple[dict[str, Rendered], list[str], list[str]]:
    """Rendered documents by output path, example templates, and problems."""
    tdir = root / TEMPLATES
    found = (
        sorted(p.relative_to(tdir).as_posix() for p in tdir.rglob("*.md.in") if p.is_file())
        if tdir.is_dir()
        else []
    )
    docs: dict[str, Rendered] = {}
    examples: list[str] = []
    problems: list[str] = []
    for rel in found:
        shown = f"{TEMPLATES}/{rel}"
        hits = [(p, s) for p in sorted(spec.templates) if (s := match_template(rel, p)) is not None]
        if len(hits) != 1:
            why = "matches no" if not hits else "matches more than one"
            problems.append(f"{shown} {why} entry of templates in {SPEC} (map it, or null)")
            continue
        pattern, stem = hits[0]
        target = spec.templates[pattern]
        if target is None:
            examples.append(shown)
            continue
        output = target.replace("*", stem)
        if output in docs:
            problems.append(f"{shown} and {docs[output].template} both render {output}")
            continue
        text = (tdir / rel).read_text(encoding="utf-8")
        rendered, p = render(text, shown, output, spec, claims, figures)
        problems += p
        if rendered is not None:
            docs[output] = rendered
    return docs, examples, problems


def build(root: Path) -> Build:
    """Compute, without writing, everything ``make report`` writes."""
    spec, problems = load_spec(root)
    result = Build(spec, problems=problems)
    allow, _ = claimcheck.load_allowlist(root / ALLOWLIST)  # claimcheck reports its problems
    result.claims, p = resolve_claims(root, spec)
    result.problems += p
    result.figures, p = draw_figures(spec, result.claims, allow)
    result.problems += p
    result.docs, result.examples, p = render_templates(root, spec, result.claims, result.figures)
    result.problems += p
    return result


def write_file(path: Path, text: str) -> bool:
    """Write UTF-8 text with LF line ends unless the file already holds exactly that."""
    data = text.encode("utf-8")
    if path.is_file() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def dump(value: Any) -> str:
    """Deterministic JSON text."""
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def run(root: Path) -> tuple[list[str], int]:
    """Build and, if nothing failed, write every output; output lines and exit status."""
    result = build(root)
    if result.problems:
        out = [f"report: {p}" for p in result.problems]
        return [*out, "report: FAIL (nothing written)"], 1
    write_file(root / REGISTRY, dump(result.registry))
    lines = [f"report: {len(result.claims)} claims resolved into {REGISTRY}"]
    for rel, svg in sorted(result.figures.items()):
        write_file(root / rel, svg)
        lines.append(f"report: drew {rel}")
    manifest = root / MANIFEST
    if result.figures or manifest.exists():
        write_file(manifest, dump(result.manifest))
        lines.append(f"report: wrote {MANIFEST} ({len(result.figures)} figures)")
    for rel, doc in sorted(result.docs.items()):
        write_file(root / rel, doc.text)
        lines.append(
            f"report: rendered {doc.template} -> {rel} ({doc.claims} claims, {doc.figures} figures)"
        )
    lines += [
        f"report: {ex} is an example (mapped to null); not rendered" for ex in result.examples
    ]
    if not result.docs:
        mapped = ", ".join(k for k, v in sorted(result.spec.templates.items()) if v) or "none"
        lines.append(f"report: no templates yet under {TEMPLATES}/ (mapped: {mapped})")
    stray = sorted(
        p.relative_to(root).as_posix()
        for p in (root / FIGURES).glob("*.svg")
        if p.relative_to(root).as_posix() not in result.figures
    )
    lines += [f"report: note: {s} is not declared in {SPEC} and not in {MANIFEST}" for s in stray]
    return lines, 0


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="claim registry, figures, and documents")
    ap.add_argument("--root", type=Path, default=REPO, help="repository root (default: this one)")
    args = ap.parse_args(argv)
    out, rc = run(args.root.resolve())
    print("\n".join(out))
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
